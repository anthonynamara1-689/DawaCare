       private void refreshDoctors() {
        UiHelper.load(this, careService::getMyDoctors, links -> {
            doctorsModel.setRowCount(0);
            for (CareLink l : links) {
                doctorsModel.addRow(new Object[]{
                    l.linkId(), "Dr. " + l.name(), l.phone(), l.info(), UiHelper.fmt(l.since())});
            }
        });
    }

    private void refreshCaregivers() {
        UiHelper.load(this, careService::getMyCaregivers, links -> {
            caregiversModel.setRowCount(0);
            long pending = 0;
            for (CareLink l : links) {
                caregiversModel.addRow(new Object[]{
                    l.linkId(), l.name(), l.phone(), l.info(), l.status(), UiHelper.fmt(l.since())});
                if ("PENDING".equals(l.status())) pending++;
            }
            int tab = tabMain.indexOfComponent(pnlCaregivers);
            tabMain.setTitleAt(tab, pending > 0 ? "My Caregivers (" + pending + " new)" : "My Caregivers");
        });
    }

    private void addDoctor() {
        UiHelper.load(this, careService::getAvailableDoctors, doctors -> {
            if (doctors.isEmpty()) {
                JOptionPane.showMessageDialog(this, "There are no other approved doctors available right now.");
                return;
            }
            DoctorOption choice = (DoctorOption) JOptionPane.showInputDialog(
                    this, "Choose a doctor to add to your care team:", "Add Doctor",
                    JOptionPane.PLAIN_MESSAGE, null, doctors.toArray(), doctors.get(0));
            if (choice != null) {
                UiHelper.run(this, () -> careService.addDoctor(choice.doctorId()), this::refreshDoctors);
            }
        });
    }

