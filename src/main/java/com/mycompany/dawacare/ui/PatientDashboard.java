    private void btnRemoveDoctorActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRemoveDoctorActionPerformed
        int linkId = UiHelper.selectedId(this, tblDoctors);
        if (linkId < 0) return;
        if (UiHelper.confirm(this, "Remove this doctor from your care team? "
                + "They will no longer be able to see your records.")) {
            UiHelper.run(this, () -> careService.removeDoctor(linkId), this::refreshDoctors);
        }
    }//GEN-LAST:event_btnRemoveDoctorActionPerformed

