    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
        int ci = cboCategory.getSelectedIndex();
        Integer categoryId = (ci > 0) ? categories.get(ci - 1).categoryId() : null;
        Object formItem = cboForm.getEditor().getItem();   // editable combo: read what's typed

        Medication m = new Medication(
            existing == null ? null : existing.medicationId(),
            categoryId, null,
            txtName.getText(),
            txtGeneric.getText(),
            formItem == null ? "" : formItem.toString(),
            txtStrength.getText(),
            txtManufacturer.getText(),
            txtDescription.getText(),
            0);

        btnSave.setEnabled(false);
        UiHelper.load(this, () -> {
            try {
                medicationService.save(m);
                return Boolean.TRUE;
            } finally {
                SwingUtilities.invokeLater(() -> btnSave.setEnabled(true));
            }
        }, ok -> {
            saved = true;
            dispose();
        });
    }//GEN-LAST:event_btnSaveActionPerformed

        public boolean isSaved() {
        return saved;
    }

