    public MedicationDialog(java.awt.Frame parent, Medication existing, List<CategoryOption> categories) {
        super(parent, true);
        this.existing = existing;
        this.categories = categories;
        initComponents();
        setLocationRelativeTo(parent);
        setTitle(existing == null ? "Add Medication" : "Edit Medication");

        cboCategory.removeAllItems();
        cboCategory.addItem("(none)");
        for (CategoryOption c : categories) cboCategory.addItem(c.name());

        lblInUse.setText(" ");
        if (existing != null) {
            txtName.setText(existing.name());
            txtGeneric.setText(existing.genericName() == null ? "" : existing.genericName());
            cboForm.setSelectedItem(existing.dosageForm());
            txtStrength.setText(existing.strength());
            txtManufacturer.setText(existing.manufacturer() == null ? "" : existing.manufacturer());
            txtDescription.setText(existing.description() == null ? "" : existing.description());

            for (int i = 0; i < categories.size(); i++) {
                if (existing.categoryId() != null && categories.get(i).categoryId() == existing.categoryId()) {
                    cboCategory.setSelectedIndex(i + 1);   // +1 because of "(none)"
                }
            }

            if (existing.usageCount() > 0) {
                txtName.setEnabled(false);
                cboForm.setEnabled(false);
                txtStrength.setEnabled(false);
                lblInUse.setText("Used in " + existing.usageCount()
                        + " prescription item(s): name, form and strength are locked.");
            }
        }
    }

