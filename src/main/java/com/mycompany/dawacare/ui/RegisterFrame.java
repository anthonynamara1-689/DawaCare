       private void showRoleCard() {
        String role = (String) cboRole.getSelectedItem();
        CardLayout cards = (CardLayout) pnlRoleDetails.getLayout();
        cards.show(pnlRoleDetails, role);
        lblStatus.setText(" ");
    }

    private void doRegister() {
        RegistrationRequest req = new RegistrationRequest(
            Role.valueOf((String) cboRole.getSelectedItem()),
            txtFullName.getText(),
            txtUsername.getText(),
            new String(txtPassword.getPassword()),
            new String(txtConfirm.getPassword()),
            txtEmail.getText(),
            txtPhone.getText(),
            txtDob.getText(),
            (String) cboGender.getSelectedItem(),
            txtAddress.getText(),
            txtEmergencyName.getText(),
            txtEmergencyPhone.getText(),
            txtLicense.getText(),
            txtSpecialization.getText(),
            txtHospital.getText());

        setBusy(true);
        lblStatus.setText("Creating account...");

        new SwingWorker<String, Void>() {
            private String error;

            @Override
            protected String doInBackground() {
                try {
                    return registrationService.register(req);
                }catch(ServiceException ex) {
                    error = ex.getMessage();
                    return null;
                }
            }

            @Override
            protected void done() {
                setBusy(false);
                String message = null;
                try {
                    message = get();
                } catch (Exception ex) {
                    error = "Unexpected error: " + ex.getMessage();
                }
                if (message == null) {
                    lblStatus.setText(error);
                    return;
                }
                JOptionPane.showMessageDialog(RegisterFrame.this, message,
                        "Registration", JOptionPane.INFORMATION_MESSAGE);
                new LoginFrame().setVisible(true);
                dispose();
            }
        }.execute();
    }

    private void setBusy(boolean busy) {
        btnRegister.setEnabled(!busy);
        btnBack.setEnabled(!busy);
        cboRole.setEnabled(!busy);
    }

