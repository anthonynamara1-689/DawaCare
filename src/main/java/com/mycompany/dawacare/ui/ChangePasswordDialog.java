    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
        char[] c1 = txtCurrent.getPassword(), c2 = txtNew.getPassword(), c3 = txtConfirm.getPassword();
        String current = new String(c1), newPw = new String(c2), confirm = new String(c3);
        Arrays.fill(c1, '\0');
        Arrays.fill(c2, '\0');
        Arrays.fill(c3, '\0');

        btnSave.setEnabled(false);
        UiHelper.load(this, () -> {
            try {
                authService.changePassword(current, newPw, confirm);
                return Boolean.TRUE;
            } finally {
                SwingUtilities.invokeLater(() -> btnSave.setEnabled(true));
            }
        }, ok -> {
            JOptionPane.showMessageDialog(this, "Your password has been changed.");
            dispose();
        });
    }//GEN-LAST:event_btnSaveActionPerformed

    

