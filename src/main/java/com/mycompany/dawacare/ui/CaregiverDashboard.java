    private void btnCancelLinkActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCancelLinkActionPerformed
        int linkId = UiHelper.selectedId(this, tblPatients);
        if (linkId < 0) return;
        if (UiHelper.confirm(this, "Cancel this request, or stop caring for this patient?")) {
            UiHelper.run(this, () -> careService.cancelPatientLink(linkId), this::refreshPatients);
        }
    }//GEN-LAST:event_btnCancelLinkActionPerformed

    private void cboPatientActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_cboPatientActionPerformed
        if (!loadingPatients) showSelectedPatient();
    }//GEN-LAST:event_cboPatientActionPerformed

    private void refreshPatients() {
        UiHelper.load(this, careService::getMyPatients, links -> {
            patientsModel.setRowCount(0);
            for (CareLink l : links) {
                patientsModel.addRow(new Object[]{
                    l.linkId(), l.name(), l.phone(), l.info(), l.status(), UiHelper.fmt(l.since())});
            }
        });
    }
        private void loadLinkedPatients() {
        UiHelper.load(this, doseService::getMyActivePatients, list -> {
            Integer previous = selectedPatientId();

            loadingPatients = true;
            linkedPatients.clear();
            linkedPatients.addAll(list);
            cboPatient.removeAllItems();
            int restore = -1;
            for (int i = 0; i < list.size(); i++) {
                cboPatient.addItem(list.get(i).fullName());
                if (previous != null && list.get(i).patientId() == previous) restore = i;
            }
            if (!list.isEmpty()) cboPatient.setSelectedIndex(restore >= 0 ? restore : 0);
            loadingPatients = false;

            showSelectedPatient();
        });
    }

    private Integer selectedPatientId() {
        int i = cboPatient.getSelectedIndex();
        return (i >= 0 && i < linkedPatients.size()) ? linkedPatients.get(i).patientId() : null;
    }

    private void showSelectedPatient() {
        Integer id = selectedPatientId();
        if (id == null) {
            dosePanel.showNothing("You have no approved patients yet. Send a request from the My Patients tab.");
        } else {
            dosePanel.showPatient(id);
        }
    }

