    private void btnSendRequestActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSendRequestActionPerformed
        String username = txtPatientUsername.getText();
        String relationship = txtRelationship.getText();
        UiHelper.run(this, () -> careService.requestPatient(username, relationship), () -> {
            txtPatientUsername.setText("");
            txtRelationship.setText("");
            JOptionPane.showMessageDialog(this,
                "Request sent. The patient must approve it from their dashboard.");
            refreshPatients();
        });
    }//GEN-LAST:event_btnSendRequestActionPerformed

