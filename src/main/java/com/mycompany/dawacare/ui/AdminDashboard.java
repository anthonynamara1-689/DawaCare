       /** An action that may fail with a user-friendly message. */
    private interface ServiceAction {
        void run() throws ServiceException;
    }

    private void runAction(ServiceAction action, String successMessage) {
        setBusy(true);
        new SwingWorker<Void, Void>() {
            private String error;

            @Override
            protected Void doInBackground() {
                try {
                    action.run();
                } catch (ServiceException ex) {
                    error = ex.getMessage();
                }
                return null;
            }

            @Override
            protected void done() {
                setBusy(false);
                try {
                    get();
                } catch (Exception ex) {
                    error = "Unexpected error: " + ex.getMessage();
                }
                if (error != null) {
                    JOptionPane.showMessageDialog(AdminDashboard.this, error,
                            "Action not allowed", JOptionPane.WARNING_MESSAGE);
                    lblStatus.setText(" ");
                } else {
                    lblStatus.setText(successMessage);
                }
                refreshAll();
            }
        }.execute();
    }

    private void refreshAll() {
        new SwingWorker<Void, Void>() {
            private List<PendingDoctor> pending;
            private List<UserSummary> users;
            private String error;

            @Override
            protected Void doInBackground() {
                try {
                    pending = adminService.getPendingDoctors();
                    users = adminService.getAllUsers();
                } catch (ServiceException ex) {
                    error = ex.getMessage();
                }
                return null;
            }

            @Override
            protected void done() {
                if (error != null) {
                    lblStatus.setText(error);
                    return;
                }
                pendingModel.setRowCount(0);
                for (PendingDoctor d : pending) {
                    pendingModel.addRow(new Object[]{
                        d.userId(), d.fullName(), d.username(), d.licenseNumber(),
                        d.specialization(), d.hospitalName(), d.email(), d.phone(),
                        fmt(d.registeredAt())});
                }
                usersModel.setRowCount(0);
                for (UserSummary u : users) {
                    usersModel.addRow(new Object[]{
                        u.userId(), u.username(), u.fullName(), u.role(), u.status(),
                        fmt(u.createdAt()), fmt(u.lastLoginAt())});
                }
                tabMain.setTitleAt(0, "Pending Doctors (" + pending.size() + ")");
            }
        }.execute();
    }

    private int selectedUserId(JTable table) {
        int row = table.getSelectedRow();
        if (row < 0) {
            JOptionPane.showMessageDialog(this, "Please select a row first.");
            return -1;
        }
        return (Integer) table.getModel().getValueAt(table.convertRowIndexToModel(row), 0);
    }

    private boolean confirm(String message) {
        return JOptionPane.showConfirmDialog(this, message, "Confirm",
                JOptionPane.YES_NO_OPTION) == JOptionPane.YES_OPTION;
    }

    private void setBusy(boolean busy) {
        btnApprove.setEnabled(!busy);
        btnReject.setEnabled(!busy);
        btnActivate.setEnabled(!busy);
        btnDeactivate.setEnabled(!busy);
    }

    private static String fmt(LocalDateTime t) {
        return t == null ? "-" : t.format(FMT);
    }

    private static DefaultTableModel readOnlyModel(String... columns) {
        return new DefaultTableModel(columns, 0) {
            @Override
            public boolean isCellEditable(int row, int col) {
                return false;   // admin can't type into the table
            }
        };
    }
