    private void btnSkipActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSkipActionPerformed
        int doseId = UiHelper.selectedId(this, tblDoses);
        if (doseId < 0) return;
        String reason = JOptionPane.showInputDialog(this,
                "Why is this dose being skipped? (optional)", "Skip dose", JOptionPane.QUESTION_MESSAGE);
        if (reason == null) return;   // user pressed Cancel
        Integer pid = patientId;
        UiHelper.run(this, () -> doseService.markSkipped(pid, doseId, reason), this::refresh);
    }//GEN-LAST:event_btnSkipActionPerformed

