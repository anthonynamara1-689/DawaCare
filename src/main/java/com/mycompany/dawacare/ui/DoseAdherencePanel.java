        /** Show doses for a patient. Pass null when the logged-in user IS the patient. */
    public void showPatient(Integer patientId) {
        this.patientId = patientId;
        this.hasPatient = true;
        setButtonsEnabled(true);
        refresh();
    }
        /** Read-only mode hides the recording buttons (used by doctors). */
    public void setReadOnly(boolean readOnly) {
        this.readOnly = readOnly;
        btnSkip.setVisible(!readOnly);
        btnTaken.setVisible(!readOnly);
    }

    /** Clear the panel, e.g. when a caregiver has no approved patients. */
    public void showNothing(String message) {
        hasPatient = false;
        dosesModel.setRowCount(0);
        adherenceModel.setRowCount(0);
        lblToday.setText(message);
        lblWeek.setText(" ");
        lblMonth.setText(" ");
        lblStatus.setText(" ");
        setButtonsEnabled(false);
    }

    public void refresh() {
        if (!hasPatient) return;
        Integer pid = patientId;
        UiHelper.load(this, () -> doseService.getOverview(pid), this::showOverview);
    }

    private void showOverview(DoseOverview o) {
        lblToday.setText("Today's doses – " + LocalDate.now().format(DAY));

        LocalDateTime now = LocalDateTime.now();
        dosesModel.setRowCount(0);
        for (DoseItem d : o.today()) {
            dosesModel.addRow(new Object[]{
                d.doseId(),
                d.scheduledAt().format(TIME),
                d.medication(),
                d.doseText(),
                d.instructions() == null ? "" : d.instructions(),
                displayStatus(d, now),
                d.takenAt() == null ? "-" : d.takenAt().format(TIME),
                d.recordedBy() == null ? "-" : d.recordedBy()});
        }
        lblStatus.setText(o.today().isEmpty() ? "No doses scheduled for today." : " ");

        showStats(lblWeek, "Last 7 days", o.last7Days());
        showStats(lblMonth, "Last 30 days", o.last30Days());

        adherenceModel.setRowCount(0);
        for (AdherenceStats s : o.byMedication30Days()) {
            adherenceModel.addRow(new Object[]{
                s.medication(), s.taken(), s.missed(), s.skipped(), s.percentText()});
        }
    }

    /** PENDING is shown as UPCOMING or DUE NOW so it's clearer for the user. */
    private String displayStatus(DoseItem d, LocalDateTime now) {
        if ("PENDING".equals(d.status())) {
            return d.scheduledAt().isAfter(now) ? "UPCOMING" : "DUE NOW";
        }
        return d.status();
    }

    private void showStats(JLabel label, String title, AdherenceStats s) {
        if (s.total() == 0) {
            label.setText(title + ": no completed doses yet");
            label.setForeground(UIManager.getColor("Label.foreground"));
            return;
        }
        label.setText(title + ": " + s.percentText() + " (" + s.taken() + " of " + s.total() + " taken)");
        double p = s.percent();
        label.setForeground(p >= 80 ? GOOD : p >= 50 ? FAIR : POOR);
    }

