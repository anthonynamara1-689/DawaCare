    private void refreshPatients() {
        UiHelper.load(this, rxService::getMyPatients, list -> {
            Integer previous = selectedAdherencePatientId();   // remember before the list changes

            patients.clear();
            patients.addAll(list);
            patientsModel.setRowCount(0);
            for (DoctorPatient p : list) {
                patientsModel.addRow(new Object[]{
                    p.patientId(),
                    p.fullName(),
                    p.gender() == null ? "-" : p.gender(),
                    p.age() == null ? "-" : p.age(),
                    p.phone() == null ? "-" : p.phone(),
                    UiHelper.fmt(p.linkedSince()),
                    p.activePrescriptions()});
            }
            fillAdherenceCombo(previous);
        });
    }
    

    private void refreshPrescriptions() {
        UiHelper.load(this, rxService::getMyPrescriptions, list -> {
            rxModel.setRowCount(0);
            for (PrescriptionSummary s : list) {
                rxModel.addRow(new Object[]{
                    s.prescriptionId(),
                    s.date(),
                    s.patientName(),
                    s.diagnosis() == null ? "-" : s.diagnosis(),
                    s.itemCount(),
                    s.status()});
            }
        });
    }

    /** Shows a prescription's items in a pop-up table. */
    private void showItems(List<PrescriptionItemView> items) {
        DefaultTableModel m = UiHelper.readOnlyModel(
            "Medication", "Dose", "Times", "Repeat", "Start", "End", "Instructions", "Status");
        for (PrescriptionItemView i : items) {
            m.addRow(new Object[]{
                i.medication(), i.doseText(), i.times(),
                PrescriptionItemRequest.repeatText(i.intervalDays()),
                i.startDate(), i.endDate(),
                i.instructions() == null ? "" : i.instructions(),
                i.status()});
        }
        JScrollPane scroll = new JScrollPane(new JTable(m));
        scroll.setPreferredSize(new Dimension(850, 220));
        JOptionPane.showMessageDialog(this, scroll, "Prescription items", JOptionPane.PLAIN_MESSAGE);
    }
    
    private void fillAdherenceCombo(Integer previousPatientId) {
        loadingAdherenceCombo = true;
        cboAdherencePatient.removeAllItems();
        int restore = -1;
        for (int i = 0; i < patients.size(); i++) {
            cboAdherencePatient.addItem(patients.get(i).fullName());
            if (previousPatientId != null && patients.get(i).patientId() == previousPatientId) restore = i;
        }
        if (!patients.isEmpty()) cboAdherencePatient.setSelectedIndex(restore >= 0 ? restore : 0);
        loadingAdherenceCombo = false;
        showAdherencePatient();
    }

    private Integer selectedAdherencePatientId() {
        int i = cboAdherencePatient.getSelectedIndex();
        return (i >= 0 && i < patients.size()) ? patients.get(i).patientId() : null;
    }

    private void showAdherencePatient() {
        Integer id = selectedAdherencePatientId();
        if (id == null) {
            dosePanel.showNothing("You have no linked patients yet.");
        } else {
            dosePanel.showPatient(id);
        }
    }

