    private void btnCancelPrescriptionActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCancelPrescriptionActionPerformed
        int rxId = UiHelper.selectedId(this, tblPrescriptions);
        if (rxId < 0) return;
        if (UiHelper.confirm(this, "Cancel this prescription? All of its upcoming doses will be cancelled.")) {
            UiHelper.run(this, () -> rxService.cancelPrescription(rxId), () -> {
                refreshPrescriptions();
                refreshPatients();
            });
        }
    }//GEN-LAST:event_btnCancelPrescriptionActionPerformed

