    private void btnNewPrescriptionActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnNewPrescriptionActionPerformed
        int patientId = UiHelper.selectedId(this, tblPatients);
        if (patientId < 0) return;

        DoctorPatient patient = patients.stream()
                .filter(p -> p.patientId() == patientId)
                .findFirst().orElse(null);
        if (patient == null) return;

        PrescriptionDialog dialog = new PrescriptionDialog(this, patient);
        dialog.setVisible(true);   // waits here until the dialog is closed (modal)

        if (dialog.isSaved()) {
            refreshPatients();
            refreshPrescriptions();
            tabMain.setSelectedComponent(pnlPrescriptions);
        }
    }//GEN-LAST:event_btnNewPrescriptionActionPerformed

