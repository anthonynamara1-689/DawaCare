    private void btnViewAdherenceActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnViewAdherenceActionPerformed
        int patientId = UiHelper.selectedId(this, tblPatients);
        if (patientId < 0) return;
        for (int i = 0; i < patients.size(); i++) {
            if (patients.get(i).patientId() == patientId) {
                cboAdherencePatient.setSelectedIndex(i);   // triggers showAdherencePatient()
                break;
            }
        }
        tabMain.setSelectedComponent(pnlAdherence);
    }//GEN-LAST:event_btnViewAdherenceActionPerformed

