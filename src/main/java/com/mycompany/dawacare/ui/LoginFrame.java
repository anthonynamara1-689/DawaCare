    private void doLogin() {
        String username = txtUsername.getText();
        char[] chars = txtPassword.getPassword();
        String password = new String(chars);
        Arrays.fill(chars, '\0');   // wipe the password array from memory

        setBusy(true);
        lblStatus.setText("Signing in...");

        new SwingWorker<User, Void>() {
            private String error;

            @Override
            protected User doInBackground() {        // runs off the UI thread
                try {
                    return authService.login(username, password);
                } catch (AuthException ex) {
                    error = ex.getMessage();
                    return null;
                }
            }

            @Override
            protected void done() {                  // back on the UI thread
                setBusy(false);
                User user = null;
                try {
                    user = get();
                } catch (Exception ex) {
                    error = "Unexpected error: " + ex.getMessage();
                }
                if (user == null) {
                    lblStatus.setText(error);
                    txtPassword.setText("");
                    txtPassword.requestFocusInWindow();
                    return;
                }
                openDashboard(user);
                dispose();
            }
        }.execute();
    }

    private void setBusy(boolean busy) {
        btnLogin.setEnabled(!busy);
        btnRegister.setEnabled(!busy);
        txtUsername.setEnabled(!busy);
        txtPassword.setEnabled(!busy);
    }

    private void openDashboard(User user) {
        JFrame dashboard = switch (user.getRole()) {
            case ADMIN     -> new AdminDashboard();
            case DOCTOR    -> new DoctorDashboard();
            case PATIENT   -> new PatientDashboard();
            case CAREGIVER -> new CaregiverDashboard();
        };
        dashboard.setVisible(true);
    }
  

