package com.mycompany.dawacare.report;

import com.lowagie.text.Document;
import com.lowagie.text.DocumentException;
import com.lowagie.text.Element;
import com.lowagie.text.Font;
import com.lowagie.text.FontFactory;
import com.lowagie.text.HeaderFooter;
import com.lowagie.text.PageSize;
import com.lowagie.text.Paragraph;
import com.lowagie.text.Phrase;
import com.lowagie.text.Rectangle;
import com.lowagie.text.pdf.PdfPCell;
import com.lowagie.text.pdf.PdfPTable;
import com.lowagie.text.pdf.PdfWriter;
import com.mycompany.dawacare.model.*;
import java.awt.Color;
import java.io.File;
import java.io.FileOutputStream;
import java.io.IOException;
import java.time.format.DateTimeFormatter;

public final class AdherenceReportPdf {

    private static final Color BRAND = new Color(0, 90, 140);
    private static final Color HEADER_BG = new Color(220, 232, 244);
    private static final Color GOOD = new Color(0, 128, 0);
    private static final Color FAIR = new Color(200, 120, 0);
    private static final Color POOR = new Color(180, 0, 0);

    private static final Font TITLE    = FontFactory.getFont(FontFactory.HELVETICA_BOLD, 20, BRAND);
    private static final Font SUBTITLE = FontFactory.getFont(FontFactory.HELVETICA, 13, Color.DARK_GRAY);
    private static final Font SECTION  = FontFactory.getFont(FontFactory.HELVETICA_BOLD, 12, BRAND);
    private static final Font LABEL    = FontFactory.getFont(FontFactory.HELVETICA_BOLD, 9, Color.BLACK);
    private static final Font TEXT     = FontFactory.getFont(FontFactory.HELVETICA, 9, Color.BLACK);
    private static final Font SMALL    = FontFactory.getFont(FontFactory.HELVETICA, 8, Color.GRAY);

    private static final DateTimeFormatter DATE      = DateTimeFormatter.ofPattern("d MMM yyyy");
    private static final DateTimeFormatter DATE_TIME = DateTimeFormatter.ofPattern("d MMM yyyy HH:mm");
    private static final DateTimeFormatter SHORT_DT  = DateTimeFormatter.ofPattern("d MMM HH:mm");
    private static final DateTimeFormatter TIME      = DateTimeFormatter.ofPattern("HH:mm");

    private AdherenceReportPdf() {}

    public static void write(AdherenceReportData d, File file) throws IOException {
        Document doc = new Document(PageSize.A4, 40, 40, 40, 50);
        try (FileOutputStream out = new FileOutputStream(file)) {
            PdfWriter.getInstance(doc, out);

            HeaderFooter footer = new HeaderFooter(
                    new Phrase("DawaCare - Confidential medical information - Page ", SMALL), true);
            footer.setAlignment(Element.ALIGN_CENTER);
            footer.setBorder(Rectangle.NO_BORDER);
            doc.setFooter(footer);   // must be set before open()

            doc.open();
            addTitle(doc);
            addPatientInfo(doc, d);
            addSummary(doc, d);
            addByMedication(doc, d);
            addCurrentMedications(doc, d);
            addHistory(doc, d);
            addNotes(doc);
            doc.close();
        } catch (DocumentException e) {
            throw new IOException("Could not build the PDF: " + e.getMessage(), e);
        }
    }

    // ===================== Sections =====================

    private static void addTitle(Document doc) throws DocumentException {
        doc.add(new Paragraph("DawaCare", TITLE));
        Paragraph sub = new Paragraph("Medication Adherence Report", SUBTITLE);
        sub.setSpacingAfter(12);
        doc.add(sub);
    }

    private static void addPatientInfo(Document doc, AdherenceReportData d) throws DocumentException {
        PatientInfo p = d.patient();
        String genderAge = (p.gender() == null ? "-" : p.gender())
                + (p.age() == null ? "" : ", " + p.age() + " years");

        PdfPTable t = new PdfPTable(new float[]{1.3f, 3f, 1.3f, 3f});
        t.setWidthPercentage(100);
        infoCell(t, "Patient", LABEL);       infoCell(t, p.fullName(), TEXT);
        infoCell(t, "Report period", LABEL); infoCell(t, d.periodStart().format(DATE) + " to " + d.periodEnd().format(DATE), TEXT);
        infoCell(t, "Gender / Age", LABEL);  infoCell(t, genderAge, TEXT);
        infoCell(t, "Generated", LABEL);     infoCell(t, d.generatedAt().format(DATE_TIME), TEXT);
        infoCell(t, "Phone", LABEL);         infoCell(t, p.phone(), TEXT);
        infoCell(t, "Generated by", LABEL);  infoCell(t, d.generatedBy(), TEXT);
        t.setSpacingAfter(8);
        doc.add(t);
    }

    private static void addSummary(Document doc, AdherenceReportData d) throws DocumentException {
        section(doc, "Summary");
        AdherenceStats s = d.overall();
        PdfPTable t = table(1, 1, 1, 1, 1, 1);
        header(t, "Doses due", "Taken", "Missed", "Skipped", "Adherence", "Rating");
        cell(t, s.total());
        cell(t, s.taken());
        cell(t, s.missed());
        cell(t, s.skipped());
        cell(t, s.percentText(), bold(ratingColor(s)));
        cell(t, rating(s), bold(ratingColor(s)));
        doc.add(t);
    }

    private static void addByMedication(Document doc, AdherenceReportData d) throws DocumentException {
        section(doc, "Adherence by medication");
        if (d.byMedication().isEmpty()) {
            doc.add(new Paragraph("No completed doses in this period.", TEXT));
            return;
        }
        PdfPTable t = table(3, 1, 1, 1, 1.2f);
        header(t, "Medication", "Taken", "Missed", "Skipped", "Adherence");
        for (AdherenceStats s : d.byMedication()) {
            cell(t, s.medication());
            cell(t, s.taken());
            cell(t, s.missed());
            cell(t, s.skipped());
            cell(t, s.percentText(), bold(ratingColor(s)));
        }
        doc.add(t);
    }

    private static void addCurrentMedications(Document doc, AdherenceReportData d) throws DocumentException {
        section(doc, "Current medications");
        if (d.currentMedications().isEmpty()) {
            doc.add(new Paragraph("No active medications.", TEXT));
            return;
        }
        PdfPTable t = table(2.4f, 1.2f, 1.3f, 1.1f, 1.1f, 1.1f, 1.8f);
        header(t, "Medication", "Dose", "Times", "Repeat", "Start", "End", "Prescribed by");
        for (MedicationLine m : d.currentMedications()) {
            String med = m.instructions() == null ? m.medication() : m.medication() + "\n(" + m.instructions() + ")";
            cell(t, med);
            cell(t, m.doseText());
            cell(t, m.times());
            cell(t, PrescriptionItemRequest.repeatText(m.intervalDays()));
            cell(t, m.startDate().format(DATE));
            cell(t, m.endDate().format(DATE));
            cell(t, "Dr. " + m.doctorName());
        }
        doc.add(t);
    }

    private static void addHistory(Document doc, AdherenceReportData d) throws DocumentException {
        section(doc, "Dose history");
        if (d.history().isEmpty()) {
            doc.add(new Paragraph("No doses in this period.", TEXT));
            return;
        }
        PdfPTable t = table(1.2f, 0.7f, 2.4f, 1.1f, 1f, 1.2f, 1.6f);
        t.setHeaderRows(1);   // repeat the header row on every page
        header(t, "Date", "Time", "Medication", "Dose", "Status", "Taken at", "Recorded by");
        for (DoseItem dose : d.history()) {
            cell(t, dose.scheduledAt().format(DATE));
            cell(t, dose.scheduledAt().format(TIME));
            cell(t, dose.medication());
            cell(t, dose.doseText());
            cell(t, dose.status(), statusFont(dose.status()));
            cell(t, dose.takenAt() == null ? "-" : dose.takenAt().format(SHORT_DT));
            cell(t, dose.recordedBy() == null ? "-" : dose.recordedBy());
        }
        doc.add(t);
    }

    private static void addNotes(Document doc) throws DocumentException {
        Paragraph p = new Paragraph(
            "How adherence is calculated: doses taken / (taken + missed + skipped). "
          + "Upcoming and cancelled doses are not counted. "
          + "Rating: Good = 80% or more, Fair = 50-79%, Poor = below 50%.", SMALL);
        p.setSpacingBefore(10);
        doc.add(p);
    }

    // ===================== Helpers =====================

    private static void section(Document doc, String title) throws DocumentException {
        Paragraph p = new Paragraph(title, SECTION);
        p.setSpacingBefore(10);
        p.setSpacingAfter(6);
        doc.add(p);
    }

    private static PdfPTable table(float... relativeWidths) {
        PdfPTable t = new PdfPTable(relativeWidths);
        t.setWidthPercentage(100);
        t.setSpacingAfter(6);
        return t;
    }

    private static void header(PdfPTable t, String... titles) {
        for (String title : titles) {
            PdfPCell c = new PdfPCell(new Phrase(title, LABEL));
            c.setBackgroundColor(HEADER_BG);
            c.setPadding(4);
            t.addCell(c);
        }
    }

    private static void cell(PdfPTable t, Object value) {
        cell(t, value, TEXT);
    }

    private static void cell(PdfPTable t, Object value, Font font) {
        PdfPCell c = new PdfPCell(new Phrase(value == null ? "-" : value.toString(), font));
        c.setPadding(4);
        t.addCell(c);
    }

    private static void infoCell(PdfPTable t, String text, Font font) {
        PdfPCell c = new PdfPCell(new Phrase(text == null ? "-" : text, font));
        c.setBorder(Rectangle.NO_BORDER);
        c.setPadding(3);
        t.addCell(c);
    }

    private static Font bold(Color color) {
        return FontFactory.getFont(FontFactory.HELVETICA_BOLD, 9, color);
    }

    private static Font statusFont(String status) {
        return switch (status) {
            case "TAKEN"   -> bold(GOOD);
            case "MISSED"  -> bold(POOR);
            case "SKIPPED" -> bold(FAIR);
            default        -> TEXT;
        };
    }

    private static String rating(AdherenceStats s) {
        Double p = s.percent();
        if (p == null) return "No data";
        return p >= 80 ? "Good" : p >= 50 ? "Fair" : "Poor";
    }

    private static Color ratingColor(AdherenceStats s) {
        Double p = s.percent();
        if (p == null) return Color.BLACK;
        return p >= 80 ? GOOD : p >= 50 ? FAIR : POOR;
    }
}